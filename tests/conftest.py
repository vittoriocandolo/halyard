@pytest.fixture
def example_dict():
    return copy.deepcopy(tomllib.loads(EXAMPLE))


def edit(d: dict, path: str, value) -> dict:
    """Set a field by its patch path, counting from 1: edit(d, "noise[2].amp[3].ms", 5.0)."""
    node = d
    parts = path.split(".")
    for i, part in enumerate(parts):
        m = re.fullmatch(r"(\w+)(?:\[(\d+)\])?", part)
        name, index = m.group(1), m.group(2)
        last = i == len(parts) - 1
        if index is None:
            if last:
                node[name] = value
            else:
                node = node[name]
        elif last:
            node[name][int(index) - 1] = value
        else:
            node = node[name][int(index) - 1]
    return d


def make(**edits):
    """The example patch with edits by path, e.g. make(**{"noise[2].rattle": 0.3})."""
    from snare.patch import from_dict

    d = tomllib.loads(EXAMPLE)
    for path, value in edits.items():
        edit(d, path, value)
    return from_dict(d)
